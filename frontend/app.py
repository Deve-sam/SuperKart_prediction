import streamlit as st
import requests
import pandas as pd
import io

# Configure page layouts and styling
st.set_page_config(
    page_title="SuperKart Sales Forecasting System",
    page_icon="🛒",
    layout="wide"
)

st.title("🛒 SuperKart Sales Forecasting System")
st.markdown("""
This interactive portal connects to the SuperKart predictive API to forecast the total sales revenue generated by products across various tier cities and outlet configurations.
""")

# Sidebar config to handle backend API Root URL
st.sidebar.header("⚙️ Connection Configuration")
backend_url = st.sidebar.text_input(
    "Backend API URL",
    value="http://backend:7860",
    help="Enter the forwarded Codespaces URL or local URL where the Flask API container is running (e.g. http://localhost:7860)"
)

# Define the prediction routes
online_endpoint = f"{backend_url}/v1/predict"
batch_endpoint = f"{backend_url}/v1/predictbatch"

# Main Layout Tabs
tab1, tab2 = st.tabs(["🎯 Real-Time Online Forecast", "📂 Batch Forecast (CSV Upload)"])

with tab1:
    st.subheader("Predict Single Product Store Sales")
    st.markdown("Fill out the attributes below to estimate the total sales for a specific product configuration:")

    # Organize inputs into columns
    col1, col2 = st.columns(2)

    with col1:
        product_id_char = st.selectbox("Product ID Prefix (Category)", ["FD", "DR", "NC"], help="FD: Food, DR: Drinks, NC: Non-Consumables")
        product_weight = st.number_input("Product Weight (kg)", min_value=1.0, max_value=30.0, value=12.5, step=0.1)
        product_sugar = st.selectbox("Product Sugar Content", ["Low Sugar", "Regular", "No Sugar"])
        product_allocated_area = st.number_input("Product Display Allocated Area", min_value=0.001, max_value=1.0, value=0.05, format="%.4f")
        product_mrp = st.number_input("Product Maximum Retail Price (MRP)", min_value=10.0, max_value=500.0, value=120.0, step=1.0)

    with col2:
        store_size = st.selectbox("Store Size", ["Medium", "High", "Small"])
        store_location = st.selectbox("Store Location City Type", ["Tier 1", "Tier 2", "Tier 3"])
        store_type = st.selectbox("Store Type", ["Supermarket Type1", "Supermarket Type2", "Departmental Store", "Food Mart"])
        store_age = st.number_input("Store Age (Years)", min_value=1, max_value=100, value=15, step=1)
        product_category = st.selectbox("Product Perishability Classification", ["Non Perishables", "Perishables"])

    # Package single payload
    payload = {
        "Product_Weight": product_weight,
        "Product_Sugar_Content": product_sugar,
        "Product_Allocated_Area": product_allocated_area,
        "Product_MRP": product_mrp,
        "Store_Size": store_size,
        "Store_Location_City_Type": store_location,
        "Store_Type": store_type,
        "Product_Id_char": product_id_char,
        "Store_Age_Years": int(store_age),
        "Product_Type_Category": product_category
    }

    if st.button("Run Real-Time Inference", type="primary"):
        with st.spinner("Communicating with prediction engine..."):
            try:
                response = requests.post(online_endpoint, json=payload)
                if response.status_code == 200:
                    prediction = response.json().get("prediction", 0.0)
                    st.success(f"### Projected Total Store Sales Revenue: **${prediction:,.2f}**")
                else:
                    st.error(f"Error Code {response.status_code}: {response.text}")
            except Exception as e:
                st.error(f"Failed to connect to the backend server at {backend_url}. Error detail: {str(e)}")

with tab2:
    st.subheader("Predict Batch Sales via CSV File Upload")
    st.markdown("Upload a CSV file containing batch store-product data to generate predictions at scale.")

    uploaded_file = st.file_uploader("Choose a CSV file", type="csv")

    if uploaded_file is not None:
        # Display uploaded preview
        df = pd.read_csv(uploaded_file)
        st.write("📝 **Uploaded Dataset Preview (First 5 Rows):**", df.head())

        # Reset buffer for posting to backend API
        uploaded_file.seek(0)

        if st.button("Generate Batch Predictions", type="primary"):
            with st.spinner("Processing batch upload and running inferences..."):
                try:
                    files = {'file': (uploaded_file.name, uploaded_file.getvalue(), 'text/csv')}
                    response = requests.post(batch_endpoint, files=files)

                    if response.status_code == 200:
                        predictions_dict = response.json()
                        predictions_series = pd.Series(predictions_dict).sort_index(key=lambda x: x.astype(int))

                        # Append projections directly back onto original dataset
                        df['Projected_Sales_Total'] = predictions_series.values

                        st.success("🎉 Batch processing completed successfully!")
                        st.write("📊 **Generated Projections Output Preview:**", df.head())

                        # Option to download final dataset as CSV
                        csv_buffer = io.BytesIO()
                        df.to_csv(csv_buffer, index=False)
                        st.download_button(
                            label="Download Complete Projections File",
                            data=csv_buffer.getvalue(),
                            file_name="SuperKart_Projections.csv",
                            mime="text/csv"
                        )
                    else:
                        st.error(f"Batch processing failed. Status Code {response.status_code}: {response.text}")
                except Exception as e:
                    st.error(f"Failed to connect to backend engine: {str(e)}")
